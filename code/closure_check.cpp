// closure_check.cpp — machine-checkable CLOSURE CERTIFICATE verifier for the
// capped AC quotient graph used by the ms14-style searches.
//
// A closure certificate for "target X is not reachable from start S with peak
// total relator length <= CAP in the SAIR 14-move model (via the ms14 capped
// quotient graph, conjugator bound K)" is:
//
//   * a sorted file of 128-bit canonical class keys (the set C), and
//   * the metadata (CAP, K, start, targets, expected size).
//
// The verifier checks, using its OWN independent implementation of the move
// semantics:
//   1. every key in the file is the canonical form of the pair it decodes to
//      (catches dump corruption), and its total length is <= CAP;
//   2. keys are sorted and pairwise distinct, and |C| equals the claimed size;
//   3. the start class is in C;
//   4. every target class is NOT in C;
//   5. C is CLOSED under every capped move: for every state in C, every
//      neighbour generated by the move enumeration (same semantics as the
//      search: c = 1 all rotations; 1 <= |c| <= min(K, (CAP-|A|-2|B|)/2)
//      junction-free conjugators, both relators replaced, both signs) is in C.
//
// 3+5 imply by induction that every class reachable from the start within the
// cap is in C; 4 then gives unreachability of the targets.  The check does NOT
// need the search program: it re-generates all moves from scratch.
//
// Usage:
//   closure_check --keys FILE --cap 28 --conj 7 --start "xxxYYYY|xyxYXY" \
//                 --target "x|y" [--target ...] --expect 8694374 [--threads 10]
#include <algorithm>
#include <atomic>
#include <chrono>
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <mutex>
#include <string>
#include <thread>
#include <vector>

using namespace std;
typedef unsigned __int128 u128;
typedef uint64_t u64;
typedef uint32_t u32;

static int CAP = 28, CONJ = 0, THREADS = 8;
static u64 EXPECT = 0;
static bool NOSYM = false;  // set by --nosym (certificates here are with sym)
static const int MAXW = 58;

static inline u128 maskn(int n) {
    if (n >= 64) return ~(u128)0;
    return (((u128)1) << (2 * n)) - 1;
}
static inline u128 invw(u128 w, int n) {
    u128 r = 0;
    for (int i = 0; i < n; i++) r = (r << 2) | (((w >> (2 * i)) & 3) ^ 1);
    return r;
}
static inline u128 phiw(u128 w, int n, int p) {
    u128 m = maskn(n);
    u128 g = (w >> 1) & (u128)0x5555555555555555ULL;
    u128 v = w & m;
    if (p & 1) v ^= (~g) & (u128)0x5555555555555555ULL & m;
    if (p & 2) v ^= g & m;
    if (p & 4) v ^= ((u128)0xAAAAAAAAAAAAAAAAULL) & m;
    return v;
}
static inline u128 canonW(u128 w, int n) {
    u128 m = maskn(n);
    u128 iw = invw(w, n);
    u128 best = w < iw ? w : iw;
    for (int k = 1; k < n; k++) {
        u128 a = ((w << (2 * k)) | (w >> (2 * (n - k)))) & m;
        u128 b = ((iw << (2 * k)) | (iw >> (2 * (n - k)))) & m;
        if (a < best) best = a;
        if (b < best) best = b;
    }
    return best;
}
static inline u128 classKey(u128 wu, int nu, u128 wv, int nv) {
    u128 best = ~(u128)0;
    int np = NOSYM ? 1 : 8;
    for (int p = 0; p < np; p++) {
        u128 a = canonW(phiw(wu, nu, p), nu);
        u128 b = canonW(phiw(wv, nv, p), nv);
        u128 k;
        if (nv < nu || (nv == nu && b < a))
            k = ((u128)nv << 122) | ((u128)nu << 116) | (b << (2 * nu)) | a;
        else
            k = ((u128)nu << 122) | ((u128)nv << 116) | (a << (2 * nv)) | b;
        if (k < best) best = k;
    }
    return best;
}

struct Wd { int n = 0; uint8_t c[64]; };

static bool parseWord(const string& s, Wd& w) {
    w.n = 0;
    for (char ch : s) {
        int l = ch == 'x' ? 0 : ch == 'X' ? 1 : ch == 'y' ? 2 : ch == 'Y' ? 3 : -1;
        if (l < 0) return false;
        if (w.n && (w.c[w.n - 1] ^ 1) == l) w.n--;
        else w.c[w.n++] = (uint8_t)l;
    }
    int lo = 0, hi = w.n - 1;
    while (lo < hi && (w.c[lo] ^ 1) == w.c[hi]) { lo++; hi--; }
    int m = hi - lo + 1;
    if (m <= 0) return false;
    if (lo) memmove(w.c, w.c + lo, m);
    w.n = m;
    return true;
}
static inline u128 packw(const uint8_t* c, int n) {
    u128 w = 0;
    for (int i = 0; i < n; i++) w = (w << 2) | c[i];
    return w;
}
static u128 keyOfSpec(const string& spec) {
    size_t bar = spec.find('|');
    Wd a, b;
    parseWord(spec.substr(0, bar), a);
    parseWord(spec.substr(bar + 1), b);
    return classKey(packw(a.c, a.n), a.n, packw(b.c, b.n), b.n);
}
static string wordStr(const Wd& w) {
    static const char* C = "xXyY";
    string s;
    for (int i = 0; i < w.n; i++) s += C[w.c[i]];
    return s;
}
static string keyStr(u128 k) {
    int na = (int)(k >> 122), nb = (int)((k >> 116) & 63);
    u128 low = k;
    uint8_t bc[64], ac[64];
    for (int i = nb - 1; i >= 0; i--) { bc[i] = (uint8_t)(low & 3); low >>= 2; }
    for (int i = na - 1; i >= 0; i--) { ac[i] = (uint8_t)(low & 3); low >>= 2; }
    Wd A; A.n = na; memcpy(A.c, ac, na);
    Wd B; B.n = nb; memcpy(B.c, bc, nb);
    return wordStr(A) + "|" + wordStr(B);
}

// ------------------------------------------------------------- hash set ----
struct Table {
    vector<u128> keys;
    vector<u32> slot;
    u64 nslots = 0;
    void init(u64 n) {
        nslots = n * 4 / 3 + 64;
        while (nslots < n + 1024) nslots++;
        slot.assign(nslots, 0);
        keys.reserve(n);
    }
    static inline u64 h(u128 k) {
        u64 x = (u64)k ^ (u64)(k >> 64) * 0x9E3779B97F4A7C15ULL;
        x ^= x >> 31; x *= 0xBF58476D1CE4E5B9ULL; x ^= x >> 29;
        x *= 0x94D049BB133111EBULL; x ^= x >> 32;
        return x;
    }
    size_t size() const { return keys.size(); }
    inline bool contains(u128 k) const {
        for (u64 i = h(k) % nslots;; i = (i + 1 == nslots) ? 0 : i + 1) {
            u32 s = slot[i];
            if (!s) return false;
            if (keys[s - 1] == k) return true;
        }
    }
    inline bool insert(u128 k) {
        for (u64 i = h(k) % nslots;; i = (i + 1 == nslots) ? 0 : i + 1) {
            u32 s = slot[i];
            if (!s) { keys.push_back(k); slot[i] = (u32)keys.size(); return true; }
            if (keys[s - 1] == k) return false;
        }
    }
};

static void cyclicReduce(Wd& w) {
    int lo = 0, hi = w.n - 1;
    while (lo < hi && (w.c[lo] ^ 1) == w.c[hi]) { lo++; hi--; }
    int m = hi - lo + 1;
    if (m <= 0) { w.n = 0; return; }
    if (lo) memmove(w.c, w.c + lo, m);
    w.n = m;
}

// independent re-implementation of the capped move enumeration
static void neighbours(const Wd& u, const Wd& v, const Table& T, u64& moves,
                       u64& bad, mutex& mu, string& firstBad) {
    for (int which = 0; which < 2; which++) {
        const Wd& A = which ? v : u;
        const Wd& B0 = which ? u : v;
        int budget = CAP - B0.n;
        if (budget <= 0) continue;
        u128 pkB0 = packw(B0.c, B0.n);
        for (int s = 0; s < 2; s++) {
            Wd B;
            B.n = B0.n;
            if (s == 0) memcpy(B.c, B0.c, B0.n);
            else for (int t = 0; t < B0.n; t++) B.c[t] = (uint8_t)(B0.c[B0.n - 1 - t] ^ 1);
            for (int i = 0; i < A.n; i++) {
                uint8_t Afirst = A.c[i], Alast = A.c[(i + A.n - 1) % A.n];
                for (int j = 0; j < B.n; j++) {
                    uint8_t Bfirst = B.c[j], Blast = B.c[(j + B.n - 1) % B.n];
                    auto check = [&](u128 wu, int nu) {
                        moves++;
                        u128 k = classKey(wu, nu, pkB0, B0.n);
                        if (!T.contains(k)) {
                            bad++;
                            lock_guard<mutex> lk(mu);
                            if (firstBad.empty()) firstBad = keyStr(k);
                        }
                    };
                    {  // c = 1
                        Wd w; w.n = 0;
                        for (int t = 0; t < A.n; t++) w.c[w.n++] = A.c[(i + t) % A.n];
                        for (int t = 0; t < B.n; t++) {
                            uint8_t l = B.c[(j + t) % B.n];
                            if (w.n && (w.c[w.n - 1] ^ 1) == l) w.n--;
                            else w.c[w.n++] = l;
                        }
                        cyclicReduce(w);
                        if (w.n > 0 && w.n <= budget) check(packw(w.c, w.n), w.n);
                    }
                    int maxc = min(CONJ, (budget - A.n - B.n) / 2);
                    if (maxc < 1) continue;
                    uint8_t c[32];
                    for (int k = 1; k <= maxc; k++) {
                        int idx[32];
                        for (int t = 0; t < k; t++) idx[t] = 0;
                        while (true) {
                            bool ok = true;
                            for (int t = 0; t < k && ok; t++) {
                                c[t] = (uint8_t)idx[t];
                                if (t && (c[t - 1] ^ 1) == c[t]) ok = false;
                            }
                            if (ok && (c[0] == (Alast ^ 1) || c[0] == Afirst)) ok = false;
                            if (ok && (c[k - 1] == (Bfirst ^ 1) || c[k - 1] == Blast)) ok = false;
                            if (ok) {
                                Wd w; w.n = 0;
                                for (int t = 0; t < A.n; t++) w.c[w.n++] = A.c[(i + t) % A.n];
                                for (int t = 0; t < k; t++) w.c[w.n++] = c[t];
                                for (int t = 0; t < B.n; t++) w.c[w.n++] = B.c[(j + t) % B.n];
                                for (int t = k - 1; t >= 0; t--) w.c[w.n++] = (uint8_t)(c[t] ^ 1);
                                check(packw(w.c, w.n), w.n);
                            }
                            int t = k - 1;
                            while (t >= 0 && idx[t] == 3) idx[t--] = 0;
                            if (t < 0) break;
                            idx[t]++;
                        }
                    }
                }
            }
        }
    }
}

int main(int argc, char** argv) {
    string keysPath, startSpec;
    vector<string> targetSpecs;
    for (int i = 1; i < argc; i++) {
        string a = argv[i];
        auto nx = [&]() { return string(argv[++i]); };
        if (a == "--keys") keysPath = nx();
        else if (a == "--cap") CAP = stoi(nx());
        else if (a == "--conj") CONJ = stoi(nx());
        else if (a == "--start") startSpec = nx();
        else if (a == "--target") targetSpecs.push_back(nx());
        else if (a == "--expect") EXPECT = stoull(nx());
        else if (a == "--threads") THREADS = stoi(nx());
        else if (a == "--nosym") NOSYM = true;
        else { fprintf(stderr, "unknown arg %s\n", a.c_str()); return 2; }
    }
    auto t0 = chrono::steady_clock::now();
    FILE* f = fopen(keysPath.c_str(), "rb");
    if (!f) { fprintf(stderr, "cannot open %s\n", keysPath.c_str()); return 2; }
    fseek(f, 0, SEEK_END);
    long sz = ftell(f);
    fseek(f, 0, SEEK_SET);
    size_t n = sz / sizeof(u128);
    vector<u128> ks(n);
    if (fread(ks.data(), sizeof(u128), n, f) != n) { fprintf(stderr, "short read\n"); return 2; }
    fclose(f);
    printf("keys file: %s (%zu keys, %ld bytes)\n", keysPath.c_str(), n, sz);
    if (EXPECT && n != EXPECT) { printf("FAIL size %zu != expected %llu\n", n, (unsigned long long)EXPECT); return 1; }
    bool sorted = true;
    for (size_t i = 1; i < n; i++) if (ks[i - 1] >= ks[i]) { sorted = false; break; }
    printf("sorted+distinct: %s\n", sorted ? "yes" : "NO");
    if (!sorted) return 1;

    // (1) canonical-form and length check
    size_t badCanon = 0, badLen = 0;
    for (size_t i = 0; i < n; i++) {
        u128 k = ks[i];
        int na = (int)(k >> 122), nb = (int)((k >> 116) & 63);
        if (na + nb > CAP) badLen++;
        u128 low = k;
        uint8_t bc[64], ac[64];
        for (int q = nb - 1; q >= 0; q--) { bc[q] = (uint8_t)(low & 3); low >>= 2; }
        for (int q = na - 1; q >= 0; q--) { ac[q] = (uint8_t)(low & 3); low >>= 2; }
        u128 recomputed = classKey(packw(ac, na), na, packw(bc, nb), nb);
        if (recomputed != k) badCanon++;
    }
    printf("canonical-form violations: %zu ; length>cap: %zu\n", badCanon, badLen);
    if (badCanon || badLen) return 1;

    Table T;
    T.init(n);
    for (u128 k : ks) T.insert(k);
    printf("hash table built (%zu states)\n", T.size());

    // (3)(4) start and targets
    u128 start = keyOfSpec(startSpec);
    bool startIn = T.contains(start);
    printf("start %s in set: %s\n", keyStr(start).c_str(), startIn ? "yes" : "NO");
    bool tgAbsent = true;
    for (auto& t : targetSpecs) {
        u128 tk = keyOfSpec(t);
        bool present = T.contains(tk);
        printf("target %s in set: %s\n", t.c_str(), present ? "YES (FAIL)" : "no");
        if (present) tgAbsent = false;
    }
    if (!startIn || !tgAbsent) { printf("VERDICT: FAIL\n"); return 1; }

    // (5) closure under all capped moves
    atomic<u64> next(0);
    atomic<u64> movesDone(0), badCount(0);
    mutex mu;
    string firstBad;
    vector<thread> pool;
    for (int t = 0; t < THREADS; t++) {
        pool.emplace_back([&]() {
            u64 myMoves = 0, myBad = 0;
            string myFirstBad;
            while (true) {
                u64 i = next.fetch_add(4096);
                if (i >= n) break;
                u64 e = min<u64>(n, i + 4096);
                for (u64 x = i; x < e; x++) {
                    u128 k = ks[x];
                    int na = (int)(k >> 122), nb = (int)((k >> 116) & 63);
                    u128 low = k;
                    uint8_t bc[64], ac[64];
                    for (int q = nb - 1; q >= 0; q--) { bc[q] = (uint8_t)(low & 3); low >>= 2; }
                    for (int q = na - 1; q >= 0; q--) { ac[q] = (uint8_t)(low & 3); low >>= 2; }
                    Wd u; u.n = na; memcpy(u.c, ac, na);
                    Wd v; v.n = nb; memcpy(v.c, bc, nb);
                    neighbours(u, v, T, myMoves, myBad, mu, myFirstBad);
                }
            }
            lock_guard<mutex> lk(mu);
            movesDone += myMoves;
            badCount += myBad;
            if (!myFirstBad.empty() && firstBad.empty()) firstBad = myFirstBad;
        });
    }
    for (auto& th : pool) th.join();
    double el = chrono::duration<double>(chrono::steady_clock::now() - t0).count();
    printf("closure: checked %llu moves from %zu states; violations: %llu",
           (unsigned long long)movesDone.load(), n, (unsigned long long)badCount.load());
    if (!firstBad.empty()) printf(" ; first violation: %s", firstBad.c_str());
    printf("\ntime: %.1fs\n", el);
    bool ok = (badCount.load() == 0);
    printf("VERDICT: %s (closed set excludes all targets => targets unreachable from start with peak <= %d)\n",
           ok ? "PASS" : "FAIL", CAP);
    return ok ? 0 : 1;
}
